/* One-pager exports (PNG, PDF, PPTX) built from the same insight objects the panel renders,
   so the file always matches the screen. No third-party libraries. */
import type { Brief, Drill } from '../engine/insight';
import { plain } from './Rich';

export interface Doc { title: string; scope: string; period: string; situation: string[]; sections: { title: string; lines: string[] }[] }

export function toDoc(v: Brief | Drill, scope: string, period: string): Doc {
  if (v.kind === 'brief') {
    const s: Doc['sections'] = [];
    if (v.conc) s.push({ title: v.conc.title, lines: v.conc.rows.map((r) => `${r.name}: ${r.value}${r.chips.length ? ' (' + r.chips.map((c) => `${c.n} ${c.v}`).join(', ') + ')' : ''}`) });
    if (v.why.length) s.push({ title: 'Why it is happening', lines: v.why.map((w) => `${w.name} ${w.v}: ${w.text}`) });
    if (v.actions.length) s.push({ title: 'What to do next', lines: v.actions.map((a, i) => `${i + 1}. ${a.site}: ${a.text} (${a.impact})`) });
    return { title: 'Manufacturing Performance Summary', scope, period, situation: [plain(v.headline), plain(v.support)], sections: s };
  }
  return {
    title: v.name, scope, period, situation: [plain(v.headline), plain(v.support)],
    sections: [
      { title: 'By site', lines: v.sites.map((s) => `${s.name}: ${s.value} (${s.v})`) },
      { title: 'Root cause', lines: [plain(v.cause)] },
      { title: 'Consequence', lines: [v.consequence] },
      { title: 'Plan', lines: v.plan.steps.map((s) => `${s.when}: ${s.text}${s.from != null ? ` (${s.from} → ${s.to})` : ''}`) },
    ],
  };
}
export const docText = (d: Doc) =>
  [d.title.toUpperCase(), `${d.scope} | ${d.period}`, '', 'SITUATION', ...d.situation,
    ...d.sections.flatMap((s) => ['', s.title.toUpperCase(), ...s.lines]), '', 'Generated by Vectron AI · illustrative figures.'].join('\n');

function dl(blob: Blob, name: string) {
  const u = URL.createObjectURL(blob), a = document.createElement('a');
  a.href = u; a.download = name; document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(u), 1500);
}
const ascii = (s: string) => String(s).replace(/₹/g, 'Rs.').replace(/[·–—−→]/g, '-').replace(/[’‘]/g, "'").replace(/[“”]/g, '"').replace(/[^\x20-\x7E]/g, '');

/* ---------------- PNG ---------------- */
export function exportPNG(d: Doc) {
  const W = 1240, scale = 2, cv = document.createElement('canvas'), x = cv.getContext('2d')!;
  const font = (w: number, s: number) => `${w} ${s}px Manrope, Arial, sans-serif`;
  const wrap = (t: string, max: number) => {
    const out: string[] = []; let line = '';
    t.split(' ').forEach((w) => { if (x.measureText(line + w).width > max && line) { out.push(line.trim()); line = ''; } line += w + ' '; });
    if (line.trim()) out.push(line.trim());
    return out;
  };
  // measure pass
  const blocks: { f: string; c: string; lines: string[]; gap: number; lh: number }[] = [];
  x.font = font(700, 22); blocks.push({ f: font(700, 22), c: '#0A1420', lines: wrap(d.situation[0], W - 120), gap: 0, lh: 30 });
  x.font = font(500, 15); blocks.push({ f: font(500, 15), c: '#3B4B60', lines: wrap(d.situation[1], W - 120), gap: 8, lh: 22 });
  d.sections.forEach((s) => {
    blocks.push({ f: font(800, 12), c: '#2550E0', lines: [s.title.toUpperCase()], gap: 26, lh: 18 });
    x.font = font(500, 14);
    blocks.push({ f: font(500, 14), c: '#0A1420', lines: s.lines.flatMap((l) => wrap(l, W - 120)), gap: 4, lh: 21 });
  });
  const H = 150 + blocks.reduce((a, b) => a + b.gap + b.lines.length * b.lh, 0) + 70;
  cv.width = W * scale; cv.height = H * scale; x.scale(scale, scale);
  const g = x.createLinearGradient(0, 0, W, 0); g.addColorStop(0, '#0B1933'); g.addColorStop(0.55, '#121F47'); g.addColorStop(1, '#332360');
  x.fillStyle = '#F4F6FA'; x.fillRect(0, 0, W, H);
  x.fillStyle = g; x.fillRect(0, 0, W, 96);
  x.fillStyle = '#fff'; x.font = font(800, 26); x.fillText(d.title, 60, 50);
  x.fillStyle = '#B8C1E6'; x.font = font(500, 14); x.fillText(`Vectron AI · ${d.scope} · ${d.period}`, 60, 76);
  x.fillStyle = '#fff'; x.beginPath(); (x as any).roundRect?.(36, 120, W - 72, H - 170, 14); x.fill();
  let y = 162;
  blocks.forEach((b) => { y += b.gap; x.font = b.f; x.fillStyle = b.c; b.lines.forEach((l) => { x.fillText(l, 60, y); y += b.lh; }); });
  x.fillStyle = '#8593A8'; x.font = font(500, 12); x.fillText(`Generated ${new Date().toLocaleString('en-IN')} · illustrative figures`, 60, H - 22);
  cv.toBlob((b) => b && dl(b, 'vectron-insight.png'), 'image/png');
}

/* ---------------- PDF (single page, standard fonts) ---------------- */
export function pdfBlob(d: Doc) {
  const W = 595, H = 842, ops: string[] = [];
  let y = 0;
  const T = (t: string, s: number, b: boolean, px: number, col = '0 0 0') =>
    ops.push(`BT /${b ? 'F1' : 'F2'} ${s} Tf ${col} rg ${px} ${y.toFixed(1)} Td (${ascii(t).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)')}) Tj ET`);
  const wrap = (t: string, s: number, b: boolean, px: number, mw: number, lead: number, col?: string) => {
    const per = Math.floor(mw / (s * 0.5)); let line = '';
    ascii(t).split(' ').forEach((w) => { if ((line + w).length > per && line) { if (y > 44) T(line.trim(), s, b, px, col); y -= lead; line = ''; } line += w + ' '; });
    if (line.trim()) { if (y > 44) T(line.trim(), s, b, px, col); y -= lead; }
  };
  ops.push(`0.043 0.098 0.2 rg 0 ${H - 66} ${W} 66 re f`);
  y = H - 34; T(d.title, 15, true, 32, '1 1 1');
  y = H - 52; T(`Vectron AI - ${d.scope} - ${d.period}`, 8.5, false, 32, '0.72 0.76 0.9');
  y = H - 96;
  wrap(d.situation[0], 12, true, 32, W - 64, 16);
  y -= 2; wrap(d.situation[1], 9.5, false, 32, W - 64, 13, '0.23 0.29 0.38');
  d.sections.forEach((s) => {
    y -= 12; if (y > 44) T(s.title.toUpperCase(), 8.5, true, 32, '0.145 0.314 0.878'); y -= 14;
    s.lines.forEach((l) => wrap(l, 9.5, false, 32, W - 64, 13));
  });
  y = 26; T(`Generated ${new Date().toLocaleString('en-IN')} - illustrative figures`, 7.5, false, 32, '0.52 0.58 0.66');
  const content = ops.join('\n');
  const objs = [
    '',
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${W} ${H}] /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 4 0 R >>`,
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
  ];
  let out = '%PDF-1.4\n';
  const offs: number[] = [];
  for (let i = 1; i <= 6; i++) { offs[i] = out.length; out += `${i} 0 obj\n${objs[i]}\nendobj\n`; }
  const xref = out.length;
  out += 'xref\n0 7\n0000000000 65535 f \n';
  for (let i = 1; i <= 6; i++) out += String(offs[i]).padStart(10, '0') + ' 00000 n \n';
  out += `trailer\n<< /Size 7 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  const by = new Uint8Array(out.length);
  for (let i = 0; i < out.length; i++) by[i] = out.charCodeAt(i) & 0xff;
  return new Blob([by], { type: 'application/pdf' });
}
export const exportPDF = (d: Doc) => dl(pdfBlob(d), 'vectron-insight.pdf');

