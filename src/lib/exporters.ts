const CRC = (() => { const t: number[] = []; for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; t[n] = c >>> 0; } return t; })();
const crc32 = (u: Uint8Array) => { let c = 0xffffffff; for (let i = 0; i < u.length; i++) c = CRC[(c ^ u[i]) & 0xff] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
const enc = (s: string) => new Uint8Array(new TextEncoder().encode(s)) as Uint8Array<ArrayBuffer>;
function zip(files: { name: string; data: Uint8Array<ArrayBuffer> }[]) {
  const u16 = (n: number) => [n & 255, (n >> 8) & 255], u32 = (n: number) => [n & 255, (n >> 8) & 255, (n >> 16) & 255, (n >> 24) & 255];
  const chunks: BlobPart[] = [], central: { name: Uint8Array<ArrayBuffer>; crc: number; len: number; off: number }[] = [];
  let off = 0;
  files.forEach((f) => {
    const nb = enc(f.name), c = crc32(f.data);
    const lh = new Uint8Array([80, 75, 3, 4, ...u16(20), ...u16(0), ...u16(0), ...u16(0), ...u16(0), ...u32(c), ...u32(f.data.length), ...u32(f.data.length), ...u16(nb.length), ...u16(0)]);
    chunks.push(lh, nb, f.data);
    central.push({ name: nb, crc: c, len: f.data.length, off });
    off += lh.length + nb.length + f.data.length;
  });
  let cdLen = 0;
  central.forEach((e) => {
    const h = new Uint8Array([80, 75, 1, 2, ...u16(20), ...u16(20), ...u16(0), ...u16(0), ...u16(0), ...u16(0), ...u32(e.crc), ...u32(e.len), ...u32(e.len), ...u16(e.name.length), ...u16(0), ...u16(0), ...u16(0), ...u16(0), ...u32(0), ...u32(e.off)]);
    chunks.push(h, e.name); cdLen += h.length + e.name.length;
  });
  chunks.push(new Uint8Array([80, 75, 5, 6, ...u16(0), ...u16(0), ...u16(central.length), ...u16(central.length), ...u32(cdLen), ...u32(off), ...u16(0)]));
  return new Blob(chunks, { type: 'application/vnd.openxmlformats-officedocument.presentationml.presentation' });
}
